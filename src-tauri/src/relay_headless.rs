//! Headless relay mode — selected automatically when the binary runs with
//! no args on a display-less host (`main.rs` dispatch), or forced with
//! `--relay` / `--headless`.
//!
//!   `noid` (bare, headless) — self-configuring: first run generates a
//!       random passphrase into `<data-dir>/relay.pass` (0600) and encrypts
//!       identity/dht keys with it (NOIDKEY1); subsequent runs read it back.
//!   `noid --relay --init [--data-dir <dir>]` — explicit first-time setup.
//!       Set `NOID_RELAY_PASSPHRASE` at init to supply your own passphrase —
//!       then no pass file is written.
//!   `noid --relay [--port <p>] [--data-dir <dir>] [--external-addr <ma>]`
//!       — passphrase resolves in order: `NOID_RELAY_PASSPHRASE` env →
//!       `<data-dir>/relay.pass` → hidden prompt (TTY only).
//!
//! Self-healing: corrupt key/config/db files are quarantined to
//! `<name>.corrupt-<ts>` and regenerated — a damaged disk never wedges the
//! node in a crash loop. A regenerated `identity.key` means a new PeerId;
//! that is logged as WARN.
//!
//! A relay runs ONLY after its passphrase "login" — the same login-gated
//! rule as the GUI app: no unlocked keys, no node, no listeners.
//!
//! Runs the same `P2PNode` as the GUI app but forced into `NodeRole::Relay`
//! with no window — suitable for always-on machines
//! (home PC, Raspberry Pi) that strengthen the network as public relays.

use anyhow::{anyhow, Result};
use std::io::Write;
use std::path::PathBuf;

use crate::p2p::{load_bootstrap_nodes, P2PNode};
use crate::security::key_store;
use crate::security::{DHTCipher, SecurityManager};
use crate::util::quarantine::quarantine;
use crate::util::rotating_log::RotatingLog;
use crate::util::tee::Tee;

/// Canonical relay listen port — matches the bundled bootstrap seed and
/// `RelayConfig::default().listen_port` (WS always binds on port + 1).
const DEFAULT_RELAY_PORT: u16 = 4020;

/// Parse `--port` and `--data-dir` out of CLI args.
fn parse_arg(args: &[String], flag: &str) -> Option<String> {
    args.iter()
        .position(|a| a == flag)
        .and_then(|i| args.get(i + 1))
        .cloned()
}

/// Read the relay passphrase, in order:
///   1. `NOID_RELAY_PASSPHRASE` env var (systemd `EnvironmentFile=` path)
///   2. `<data-dir>/relay.pass` — auto-generated by `--init`, mode 0600
///   3. hidden stdin prompt (manual runs without a pass file)
///
/// On a non-interactive stdin (systemd, nohup, CI) a missing passphrase is a
/// hard error with instructions — never a silent block on a phantom prompt.
fn read_passphrase(data_dir: &std::path::Path, prompt: &str) -> Result<String> {
    if let Ok(p) = std::env::var("NOID_RELAY_PASSPHRASE") {
        if !p.is_empty() {
            return Ok(p);
        }
    }
    let pass_file = data_dir.join("relay.pass");
    if pass_file.exists() {
        let p = std::fs::read_to_string(&pass_file)
            .map_err(|e| anyhow!("Failed to read {}: {}", pass_file.display(), e))?;
        let p = p.trim().to_string();
        if !p.is_empty() {
            return Ok(p);
        }
    }
    use std::io::IsTerminal;
    if !std::io::stdin().is_terminal() {
        return Err(anyhow!(
            "No relay passphrase available non-interactively. Provide one via \
             NOID_RELAY_PASSPHRASE, <data-dir>/relay.pass, or run once on a \
             terminal so it can be prompted."
        ));
    }
    print!("{}", prompt);
    std::io::stdout().flush().ok();
    let pass = rpassword::read_password()
        .map_err(|e| anyhow!("Failed to read passphrase: {}", e))?;
    Ok(pass)
}

/// Write `relay.pass` with owner-only permissions (0600). Fails rather than
/// overwrite an existing file — a pass file is only written once, at init.
fn save_pass_file(path: &std::path::Path, pass: &str) -> Result<()> {
    let mut opts = std::fs::OpenOptions::new();
    opts.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        opts.mode(0o600);
    }
    let mut f = opts
        .open(path)
        .map_err(|e| anyhow!("Failed to create {}: {}", path.display(), e))?;
    f.write_all(pass.as_bytes())
        .map_err(|e| anyhow!("Failed to write {}: {}", path.display(), e))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
            .map_err(|e| anyhow!("Failed to chmod {}: {}", path.display(), e))?;
    }
    #[cfg(windows)]
    {
        // Restrict to the owner only — parity with unix 0600. icacls strips
        // inherited ACLs and grants the current user read/write.
        let status = std::process::Command::new("icacls")
            .arg(path)
            .args(["/inheritance:r", "/grant:r"])
            .arg(format!("{}:(R,W)", std::env::var("USERNAME").unwrap_or_default()))
            .output()
            .map_err(|e| anyhow!("icacls failed to start: {}", e))?;
        if !status.status.success() {
            log::warn!(
                "icacls on {} failed: {}",
                path.display(),
                String::from_utf8_lossy(&status.stderr)
            );
        }
    }
    Ok(())
}

/// `--init`: create (or re-wrap) the relay's passphrase-protected key store.
/// Existing plaintext key files are migrated in place — the relay keeps its
/// PeerId across the security upgrade.
///
/// Passphrase source at init:
///   - `NOID_RELAY_PASSPHRASE` set → use it, no pass file written (the
///     operator manages the secret via their service manager).
///   - otherwise → generate 32 random bytes (hex), write to `relay.pass`
///     (0600). Unattended restarts read it back automatically.
fn init_relay(data_dir: &std::path::Path) -> Result<()> {
    if data_dir.join("true_pin.hash").exists() && key_store::is_encrypted(&data_dir.join("identity.key")) {
        println!("Relay already initialized — nothing to do.");
        return Ok(());
    }

    // Partially-initialized/corrupt cluster (e.g. true_pin.hash present but
    // identity.key missing): move the leftovers aside first — otherwise a
    // stale relay.pass or salt.bin would break the fresh init below.
    if data_dir.join("true_pin.hash").exists() || data_dir.join("salt.bin").exists() {
        log::warn!("Incomplete key cluster detected — quarantining leftovers before init");
        quarantine_key_cluster(data_dir)?;
    }

    let (pass1, from_env) = match std::env::var("NOID_RELAY_PASSPHRASE") {
        Ok(p) if !p.is_empty() => (p, true),
        _ => {
            let mut bytes = [0u8; 32];
            rand::RngCore::fill_bytes(&mut rand::thread_rng(), &mut bytes);
            (hex::encode(bytes), false)
        }
    };

    if !from_env {
        let pass_path = data_dir.join("relay.pass");
        save_pass_file(&pass_path, &pass1)?;
        println!("Generated relay passphrase -> {}", pass_path.display());
        println!("  (mode 0600, owner-only — required for unattended restarts)");
        println!("  For stronger isolation: set NOID_RELAY_PASSPHRASE, delete relay.pass.");
    }

    let mut security = SecurityManager::new(data_dir.to_path_buf());
    security.derive_key(&pass1)?; // creates salt.bin
    security.save_true_pin_hash(&pass1)?; // true_pin.hash (verification on unlock)
    let master_key = security.get_master_key()?;

    // identity.key / dht.key — migrate valid plaintext (keeps PeerId);
    // a corrupt file is quarantined and regenerated via load_or_regen_key.
    let as_err = |e: UnlockError| match e {
        UnlockError::Fatal(e) | UnlockError::Corrupt(e) => e,
    };
    load_or_regen_key(&data_dir.join("identity.key"), &master_key, "identity")
        .map_err(as_err)?;
    load_or_regen_key(&data_dir.join("dht.key"), &master_key, "dht").map_err(as_err)?;

    println!("Relay key store initialized in {}", data_dir.display());
    println!("Start it with: noid --data-dir {} (or bare `noid` on a headless host)", data_dir.display());
    Ok(())
}

/// Why unlocking the key store failed.
#[derive(Debug)]
enum UnlockError {
    /// Passphrase missing or wrong — an auth barrier, never healed silently.
    Fatal(anyhow::Error),
    /// Stored material is unreadable — the file gets quarantined and
    /// regenerated so a damaged disk never wedges the node in a crash loop.
    Corrupt(anyhow::Error),
}

/// Unlock the key store with the passphrase and return decrypted node keys
/// plus the master key (used to field-encrypt mailbox.db and the peer cache).
/// Corrupt `identity.key`/`dht.key` files are quarantined and regenerated
/// in place — the node comes up, with a loud WARN when the PeerId changes.
fn unlock_keys(
    data_dir: &std::path::Path,
) -> std::result::Result<(libp2p::identity::Keypair, DHTCipher, [u8; 32]), UnlockError> {
    let passphrase = read_passphrase(data_dir, "Relay passphrase: ")
        .map_err(UnlockError::Fatal)?;
    let mut security = SecurityManager::new(data_dir.to_path_buf());
    match security.verify_true_pin(&passphrase) {
        Ok(true) => {}
        Ok(false) => {
            return Err(UnlockError::Fatal(anyhow!("Invalid relay passphrase")))
        }
        // Corrupt true_pin.hash — the whole key cluster is unusable.
        Err(e) => {
            return Err(UnlockError::Corrupt(anyhow!(
                "true_pin.hash unreadable: {}",
                e
            )))
        }
    }
    security
        .derive_key(&passphrase)
        .map_err(|e| UnlockError::Corrupt(anyhow!("salt.bin unusable: {}", e)))?;
    let master_key = security
        .get_master_key()
        .map_err(|e| UnlockError::Corrupt(anyhow!("master key unavailable: {}", e)))?;

    // load_or_migrate handles legacy plaintext key files from pre-upgrade
    // installs; a corrupt file is quarantined and regenerated — for
    // identity.key that means a NEW PeerId, logged loudly.
    let id_bytes = load_or_regen_key(&data_dir.join("identity.key"), &master_key, "identity")?;
    let local_key = libp2p::identity::Keypair::from_protobuf_encoding(&id_bytes)
        .map_err(|e| {
            let _ = quarantine(&data_dir.join("identity.key"));
            UnlockError::Corrupt(anyhow!("identity key decode: {}", e))
        })?;
    let dht_bytes = load_or_regen_key(&data_dir.join("dht.key"), &master_key, "dht")?;
    let dht_cipher = DHTCipher::from_private_bytes(&dht_bytes).map_err(|e| {
        let _ = quarantine(&data_dir.join("dht.key"));
        UnlockError::Corrupt(anyhow!("dht key decode: {}", e))
    })?;

    Ok((local_key, dht_cipher, master_key))
}

/// Load a key file; on ANY read/decrypt failure quarantine it and generate
/// fresh material — a corrupt key must not wedge the node. PeerId changes
/// when this regenerates identity.key, so the WARN is deliberate.
fn load_or_regen_key(
    path: &std::path::Path,
    master_key: &[u8; 32],
    kind: &str,
) -> std::result::Result<Vec<u8>, UnlockError> {
    let mut generated = false;
    let bytes = key_store::load_or_regen(
        path,
        master_key,
        || match kind {
            "identity" => libp2p::identity::Keypair::generate_ed25519()
                .to_protobuf_encoding()
                .map_err(|e| anyhow!("keypair encode: {}", e)),
            _ => Ok(DHTCipher::new().private_key_bytes().to_vec()),
        },
        |raw| match kind {
            "identity" => libp2p::identity::Keypair::from_protobuf_encoding(raw).is_ok(),
            _ => raw.len() == 32,
        },
        &mut generated,
    )
    .map_err(UnlockError::Fatal)?;
    if generated && kind == "identity" {
        log::warn!("REGENERATED identity — relay PeerId changed");
    }
    Ok(bytes)
}

/// Move every file of the key cluster aside — called when salt/true_pin is
/// corrupt and the cluster cannot be unlocked at all. Files encrypted under
/// the old master key (databases, peer cache) go too: with a new master key
/// they are undecryptable dead weight that would fail opaquely later.
fn quarantine_key_cluster(data_dir: &std::path::Path) -> Result<()> {
    for name in [
        "salt.bin",
        "identity.key",
        "dht.key",
        "true_pin.hash",
        "relay.pass",
        "noid.db",
        "mailbox.db",
        "peer_cache.json",
    ] {
        quarantine(&data_dir.join(name))?;
    }
    Ok(())
}

/// Run a headless relay node. Blocks until the process is killed.
///
/// Fully self-configuring: a bare `noid` on a headless host initializes its
/// key store, picks the canonical port and heals corrupt state files — no
/// `--init`/`--port`/`--data-dir` flags required.
pub async fn run(args: &[String]) -> anyhow::Result<()> {
    let data_dir = parse_arg(args, "--data-dir")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            dirs::config_dir()
                .unwrap_or_else(|| PathBuf::from("."))
                .join("noid-relay")
        });
    std::fs::create_dir_all(&data_dir)?;
    // stderr + bounded <data-dir>/relay.log (10 MiB, 2 archives).
    env_logger_setup(&data_dir);

    // Single instance: a second relay must fail loudly instead of fighting
    // for the same listen ports (double-bind = silent packet loss).
    // The guard removes the file on a clean exit; after a kill the next
    // start reclaims it once the recorded PID is gone.
    let _instance_lock =
        crate::util::instance_lock::InstanceLock::acquire(&data_dir, "relay.lock").map_err(|e| {
            anyhow!(
                "Relay already running in {} — {}",
                data_dir.display(),
                e
            )
        })?;

    if args.iter().any(|a| a == "--init") {
        return init_relay(&data_dir);
    }

    // First run: initialize the passphrase-protected key store automatically.
    if !data_dir.join("true_pin.hash").exists() {
        log::info!(
            "First relay run — generating passphrase (relay.pass, mode 0600) and keys"
        );
        init_relay(&data_dir)?;
    }

    let (local_key, dht_cipher, master_key) = match unlock_keys(&data_dir) {
        Ok(k) => k,
        Err(UnlockError::Fatal(e)) => return Err(e),
        Err(UnlockError::Corrupt(e)) => {
            // Cluster-level damage (salt/true_pin): quarantine everything
            // and re-init from scratch — the relay gets a new PeerId.
            log::error!("Key store corrupt ({}), quarantining cluster and re-initializing", e);
            quarantine_key_cluster(&data_dir)?;
            init_relay(&data_dir)?;
            unlock_keys(&data_dir).map_err(|e| match e {
                UnlockError::Fatal(e) | UnlockError::Corrupt(e) => e,
            })?
        }
    };

    // Port: explicit --port wins; an existing relay_config.json governs;
    // on a fresh dir the canonical relay port 4010 applies (matches the
    // bundled bootstrap seed and avoids the GUI default 4001).
    let port: Option<u16> = parse_arg(args, "--port").and_then(|p| p.parse().ok());
    let port = port.or_else(|| {
        (!data_dir.join("relay_config.json").exists()).then_some(DEFAULT_RELAY_PORT)
    });

    let mut node =
        P2PNode::new_relay_with_keys(&data_dir, local_key, dht_cipher, port, master_key).await?;

    // --external-addr /ip4/1.2.3.4/tcp/4001 — public address advertised to
    // clients (invites, kad provider records, RESERVE responses). Required
    // on a fresh VPS before any AutoNAT observer exists to confirm it.
    if let Some(ext) = parse_arg(args, "--external-addr") {
        match ext.parse::<libp2p::Multiaddr>() {
            Ok(addr) => {
                node.register_external_addr(addr.clone());
                println!("External address: {addr}");
            }
            Err(e) => log::warn!("Invalid --external-addr '{}': {}", ext, e),
        }
    }

    println!("Noid relay node (headless)");
    println!("Peer ID: {}", node.peer_id);
    println!("Data dir: {}", data_dir.display());
    println!(
        "Listen port: {} (TCP + WebSocket)",
        node.relay_config.listen_port
    );

    // Bootstrap from the same bootstrap_nodes.json mechanism.
    let bootstrap_nodes = load_bootstrap_nodes(&data_dir);
    if !bootstrap_nodes.is_empty() {
        if let Err(e) = node.bootstrap(bootstrap_nodes) {
            log::warn!("Bootstrap failed: {}", e);
        }
    } else {
        log::info!("No bootstrap nodes — this relay is reachable standalone");
    }

    // Warm start: reconnect to peers remembered from the previous run.
    node.seed_from_peer_cache();

    // Mailbox storage: the node opened its own mailbox.db in the data dir
    // (see P2PNode::with_config) — envelopes are E2EE, so the relay can
    // store/forward for offline peers.
    let (event_tx, mut event_rx) = tokio::sync::mpsc::channel::<crate::p2p::P2PEvent>(100);
    let (_cmd_tx, cmd_rx) = tokio::sync::mpsc::channel::<crate::p2p::P2PCommand>(100);

    let mut node_task = tokio::spawn(async move { node.run(event_tx, cmd_rx).await });

    // Drain events to the log so the channel never fills up.
    loop {
        tokio::select! {
            event = event_rx.recv() => {
                match event {
                    Some(crate::p2p::P2PEvent::NewListenAddr(addr)) => {
                        println!("Listening on {addr}");
                    }
                    Some(crate::p2p::P2PEvent::PeerConnected(peer)) => {
                        log::debug!("Peer connected: {peer}");
                    }
                    Some(crate::p2p::P2PEvent::RelayStatusChanged { status }) => {
                        println!(
                            "Relay status: nat={:?} relaying={} inbound_res={} circuits={} known_relays={}",
                            status.nat_status,
                            status.is_relaying,
                            status.inbound_reservations,
                            status.active_circuits,
                            status.known_relays
                        );
                    }
                    Some(_) => {}
                    None => {
                        log::info!("Event channel closed, shutting down relay");
                        break;
                    }
                }
            }
            res = &mut node_task => {
                match res {
                    Ok(inner) => log::info!("Relay node stopped: {:?}", inner),
                    Err(e) => log::error!("Relay node task failed: {}", e),
                }
                break;
            }
        }
    }
    Ok(())
}

/// stderr logger; when `<data-dir>/relay.log` can be opened, output is also
/// teed there through `RotatingLog` (10 MiB cap, 2 archives) so unattended
/// relays never grow an unbounded out.log.
fn env_logger_setup(data_dir: &std::path::Path) {
    let mut builder =
        env_logger::Builder::from_env(env_logger::Env::default().default_filter_or("info"));
    // Privacy: strip IPs and shorten PeerIds in every log line.
    builder.format(|buf, record| {
        writeln!(buf, "{}", crate::log_redact::format_record(record))
    });
    if let Ok(log) = RotatingLog::open(&data_dir.join("relay.log")) {
        builder.target(env_logger::Target::Pipe(Box::new(Tee::new(
            std::io::stderr(),
            log,
        ))));
    }
    builder.init();
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Bare-init on a fresh dir must produce the full self-contained file
    /// set: salt, pin hash, both keys (envelope format) and relay.pass.
    #[test]
    fn init_creates_full_key_cluster() {
        let dir = tempfile::tempdir().unwrap();
        init_relay(dir.path()).unwrap();
        for f in [
            "salt.bin",
            "true_pin.hash",
            "identity.key",
            "dht.key",
            "relay.pass",
        ] {
            assert!(dir.path().join(f).exists(), "missing {}", f);
        }
        assert!(key_store::is_encrypted(&dir.path().join("identity.key")));
        assert!(key_store::is_encrypted(&dir.path().join("dht.key")));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(dir.path().join("relay.pass"))
                .unwrap()
                .permissions()
                .mode();
            assert_eq!(mode & 0o777, 0o600);
        }
    }

    /// Second init on a healthy cluster is a no-op and preserves the PeerId.
    #[test]
    fn init_is_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        init_relay(dir.path()).unwrap();
        let (k1, _, _) = unlock_keys(dir.path()).unwrap();
        init_relay(dir.path()).unwrap();
        let (k2, _, _) = unlock_keys(dir.path()).unwrap();
        assert_eq!(
            libp2p::PeerId::from(k1.public()),
            libp2p::PeerId::from(k2.public())
        );
    }

    /// A corrupt encrypted identity.key is quarantined and regenerated —
    /// the node heals with a new PeerId and the rest of the cluster intact.
    #[test]
    fn corrupt_identity_key_is_quarantined_and_regenerated() {
        let dir = tempfile::tempdir().unwrap();
        init_relay(dir.path()).unwrap();
        let (k1, _, _) = unlock_keys(dir.path()).unwrap();
        let id_path = dir.path().join("identity.key");
        std::fs::write(&id_path, b"NOIDKEY1-corrupt-garbage").unwrap();
        let (k2, _, _) = unlock_keys(dir.path()).unwrap();
        assert_ne!(
            libp2p::PeerId::from(k1.public()),
            libp2p::PeerId::from(k2.public())
        );
        // Quarantine kept the evidence and regenerated a valid envelope.
        let quarantined: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .filter_map(|e| e.ok())
            .filter(|e| e.file_name().to_string_lossy().contains("identity.key.corrupt-"))
            .collect();
        assert_eq!(quarantined.len(), 1);
        assert!(key_store::is_encrypted(&id_path));
        // salt/passphrase survived — same true_pin verification path.
        assert!(dir.path().join("true_pin.hash").exists());
        assert!(dir.path().join("relay.pass").exists());
    }

    /// Legacy plaintext identity.key migrates keeping the PeerId.
    #[test]
    fn plaintext_identity_migrates_keeping_peer_id() {
        let dir = tempfile::tempdir().unwrap();
        // Simulate a pre-upgrade install: plaintext protobuf key + cluster.
        let keypair = libp2p::identity::Keypair::generate_ed25519();
        let expected_peer = libp2p::PeerId::from(keypair.public());
        init_relay(dir.path()).unwrap();
        // Overwrite identity.key with legacy plaintext; cluster stays.
        std::fs::write(
            dir.path().join("identity.key"),
            keypair.to_protobuf_encoding().unwrap(),
        )
        .unwrap();
        let (k, _, _) = unlock_keys(dir.path()).unwrap();
        assert_eq!(libp2p::PeerId::from(k.public()), expected_peer);
        assert!(key_store::is_encrypted(&dir.path().join("identity.key")));
    }

    /// Garbage plaintext must NOT be wrapped into an envelope — it is
    /// quarantined and replaced, healing locally without a cluster reset.
    #[test]
    fn garbage_plaintext_identity_is_regenerated() {
        let dir = tempfile::tempdir().unwrap();
        init_relay(dir.path()).unwrap();
        std::fs::write(dir.path().join("identity.key"), b"not-a-keypair").unwrap();
        // Must heal inside unlock (Corrupt would mean a full cluster reset).
        let (k, _, _) = unlock_keys(dir.path()).unwrap();
        assert!(key_store::is_encrypted(&dir.path().join("identity.key")));
        let _ = libp2p::PeerId::from(k.public());
    }

    #[test]
    fn parse_arg_finds_value() {
        let args = vec![
            "noid".to_string(),
            "--data-dir".to_string(),
            "/tmp/x".to_string(),
        ];
        assert_eq!(parse_arg(&args, "--data-dir").as_deref(), Some("/tmp/x"));
        assert_eq!(parse_arg(&args, "--port"), None);
    }
}
